export function matchScript(text) {
  const q = (text || '').trim().toLowerCase()
  if (!q) return FALLBACK
  for (const s of SCRIPT) {
    if (s.triggers.some(kw => q.includes(kw.toLowerCase()))) return s
  }
  return FALLBACK
}

